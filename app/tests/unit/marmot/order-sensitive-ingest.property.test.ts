// VQ-S4-015 / replay-FIFO assumption: AC-ORDER-3's own wording says
// "independent of replay order or count". The `rollbackCounts` axis below
// varies COUNT (1, 2, 3 rollback cycles) but deliberately does NOT permute
// the internal read ORDER of multiple messages queued within a single cycle's
// `replayQueue` — because `EpochResolver.rollbackAndReplay` (epochResolver.ts)
// currently reads `this.snapshot.replayQueue` by plain array spread, i.e. the
// queue is FIFO-by-insertion, not a priority/reordering structure. There is
// no free ordering variable to permute within one cycle: a single
// `replayQueue` always yields its queued application messages in the exact
// order they were appended. If `replayQueue` (or `rollbackAndReplay`'s
// consumption of it) is EVER changed to reorder, prioritize, or batch-merge
// entries from multiple queues, this test's count-only axis stops being a
// faithful stand-in for "independent of replay order" and MUST be
// re-permuted to vary intra-cycle message order explicitly, the same way
// AC-ORDER-1/2 permute inter-message arrival order.
describe('AC-ORDER-3: onApplicationMessage stays a zero-authenticity-side-effect no-op across competing-commit rollback/replay, independent of replay count', () => {
  const rollbackCounts = [1, 2, 3];

  it.each(rollbackCounts.map((count) => ({ count })))(
    'rollback count = $count: the dispatcher delivers every replayed message exactly once via authenticatedApplicationMessage, identically whether onApplicationMessage is wired or omitted',
    async ({ count }) => {
      async function run(wireCallback: boolean) {
        const { group, setOutcome } = makeCombinedFakeGroup();
        const senderPubkey = 'aa'.repeat(32);

        const handleSpy = vi.fn();
        const dispatcher = createDispatcher([{ kind: 9, handle: handleSpy }]);
        dispatcher.subscribe(group, makeCtx(`order3-${crypto.randomUUID()}`));

        const onApplicationMessage = vi.fn();
        const resolver = new EpochResolver(group, wireCallback ? { onApplicationMessage } : {});

        for (let cycle = 0; cycle < count; cycle++) {
          const winId = `commit-bbb-c${cycle}-${wireCallback}`;
          const loseId = `commit-aaa-c${cycle}-${wireCallback}`;
          const appId = `app-c${cycle}-${wireCallback}`;

          setOutcome(winId, { type: 'newState' });
          setOutcome(loseId, { type: 'skippedPastEpoch' });
          setOutcome(appId, { type: 'legitimate', senderPubkey });

          // A higher-id commit processes first (snapshot taken, grace timer
          // started)...
          await resolver.ingestEvent(makeRawEvent(winId, { created_at: 1000 }));
          // ...an application message arrives inside the grace window...
          await resolver.ingestEvent(makeRawEvent(appId, { created_at: 1000 }));
          // ...then a deterministically-LOWER competing commit arrives.
          // marmot-ts reports it 'skipped: past-epoch'; the resolver detects
          // it should have won and rolls back + replays [loseId, appId] —
          // re-emitting the application message through ingest() again.
          await resolver.ingestEvent(makeRawEvent(loseId, { created_at: 1000 }));
        }

        resolver.dispose();
        return { handleSpy, onApplicationMessage };
      }

      const withCallback = await run(true);
      const withoutCallback = await run(false);

      // The dispatcher's delivered call count is identical whether or not
      // onApplicationMessage is wired — its presence has zero effect on the
      // authenticity-delivery outcome. (The dispatcher's own rumor-id LRU
      // collapses the replay's re-emission to a single handler call per cycle.)
      expect(withCallback.handleSpy.mock.calls.length).toBe(count);
      expect(withoutCallback.handleSpy.mock.calls.length).toBe(count);

      // onApplicationMessage, when wired, IS invoked (not dead code) — but
      // every rumor it receives structurally lacks any authenticity/sender-
      // trust field, so it cannot itself establish or affect authenticity.
      // VQ-S4-016 (round-1 mutation-testing finding): an earlier version of
      // this assertion only checked `toHaveBeenCalled()` (at least once) —
      // a hand-applied mutation that fired an EXTRA, bogus onApplicationMessage
      // invocation for the winning-commit ('newState') result during replay
      // slipped through undetected, because the extra call's payload also
      // happened to lack an 'authenticity' key. Pinning the EXACT count below
      // (2 per cycle: one at the message's initial ingest, one when the
      // grace-window replay re-ingests it — NOT the same 1-per-cycle count as
      // the dispatcher's handleSpy above, which collapses the replay via its
      // own rumor-id LRU; EpochResolver's onApplicationMessage callback has no
      // such dedup of its own) closes that gap.
      expect(withCallback.onApplicationMessage.mock.calls.length).toBe(count * 2);
      for (const call of withCallback.onApplicationMessage.mock.calls) {
        expect(Object.keys(call[0] as object)).not.toContain('authenticity');
      }

      // In production configuration (callback omitted, exactly as
      // welcomeSubscription.ts constructs its resolver), no such callback
      // ever fires.
      expect(withoutCallback.onApplicationMessage).not.toHaveBeenCalled();
    },
  );
});

