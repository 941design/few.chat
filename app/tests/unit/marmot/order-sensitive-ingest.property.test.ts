describe('AC-ORDER-2 (EpochResolver): a rejected:unauthenticated-sender outcome is never added to the future/retry buffer, at any position in the sequence', () => {
  type StepId = 'U1' | 'S1' | 'P1' | 'R1';
  const steps: StepId[] = ['U1', 'S1', 'P1', 'R1'];
  const allOrderings = permutations(steps);

  it.each(allOrderings.map((ordering, index) => ({ index, ordering })))(
    'ordering #$index ($ordering): R1 is ingested exactly once, U1 is retried',
    async ({ ordering }) => {
      const { group, ingestCalls, setOutcome } = makeCombinedFakeGroup();
      setOutcome('U1', { type: 'unreadable' });
      setOutcome('S1', { type: 'skippedOther' });
      setOutcome('P1', { type: 'legitimate', senderPubkey: 'dd'.repeat(32) });
      setOutcome('R1', { type: 'rejectedUnauth', senderPubkey: 'ee'.repeat(32), claimedPubkey: 'ff'.repeat(32) });
      setOutcome('P2-trigger', { type: 'legitimate', senderPubkey: 'dd'.repeat(32) });

      const onApplicationMessage = vi.fn();
      const resolver = new EpochResolver(group, { onApplicationMessage });

      for (const id of ordering) {
        await resolver.ingestEvent(makeRawEvent(id));
      }
      // Trailing flush-trigger: an applicationMessage always follows the
      // permuted sequence, guaranteeing flushFutureBuffer() runs at least
      // once after R1's position, whatever that position was.
      await resolver.ingestEvent(makeRawEvent('P2-trigger', { created_at: 2000 }));
      resolver.dispose();

      // U1 (genuinely unreadable) IS retried — proves the flush mechanism
      // actually ran and the property below isn't vacuously true.
      const u1Count = ingestCalls.flat().filter((e) => e.id === 'U1').length;
      expect(u1Count).toBeGreaterThanOrEqual(2);

      // R1 (terminal rejection) is NEVER retried — ingested exactly once, on
      // its own originating call, regardless of where it sits in the sequence.
      const r1Count = ingestCalls.flat().filter((e) => e.id === 'R1').length;
      expect(r1Count).toBe(1);
    },
  );
});

describe('AC-ORDER-2 (welcomeSubscription, real subscribeToGroupMessages + real EpochResolver): un-mark-on-buffered logic never fires for a rejected:unauthenticated-sender outcome', () => {
  const interleavings: Array<Array<'U' | 'U-redeliver' | 'R' | 'R-redeliver'>> = [
    ['U', 'R', 'U-redeliver', 'R-redeliver'],
    ['R', 'U', 'R-redeliver', 'U-redeliver'],
    ['U', 'U-redeliver', 'R', 'R-redeliver'],
    ['R', 'R-redeliver', 'U', 'U-redeliver'],
  ];

  it.each(interleavings.map((order, index) => ({ index, order })))(
    'interleaving #$index ($order)',
    async ({ order }) => {
      const groupId = `order2-welcome-${crypto.randomUUID()}`;
      const uId = `${groupId}-U`;
      const rId = `${groupId}-R`;
      const { group, ingestCalls, setOutcome } = makeCombinedFakeGroup();
      setOutcome(uId, { type: 'unreadable' });
      setOutcome(rId, { type: 'rejectedUnauth', senderPubkey: 'aa'.repeat(32), claimedPubkey: 'bb'.repeat(32) });

      const { ndk, liveHandlers } = makeFakeNdkWithHistorical([]);
      const unsubscribe = await subscribeToGroupMessages(groupId, ['wss://r'], group, ndk as never);

      for (const step of order) {
        const id = step.startsWith('U') ? uId : rId;
        liveHandlers[0](makeRawEvent(id));
        await flushPromises();
      }
      unsubscribe();

      // U's redelivery reaches ingest() AGAIN — un-marked because 'unreadable'
      // → buffered:true. Proves the mechanism is exercised, not vacuous.
      expect(ingestCalls.flat().filter((e) => e.id === uId).length).toBe(2);

      // R's redelivery does NOT reach ingest() again — the rejected outcome
      // (buffered:false) leaves the raw event id permanently marked seen.
      expect(ingestCalls.flat().filter((e) => e.id === rId).length).toBe(1);
    },
  );
});

