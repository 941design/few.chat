describe('AC-ORDER-1 (dispatcher layer): a sender-mismatched rumor never poisons the per-group rumor-id LRU; the legitimate rumor sharing that id is processed exactly once, for every arrival order', () => {
  const legitPubkey = 'bb'.repeat(32);
  const attackerPubkey = 'aa'.repeat(32);
  const sharedId = 'order1-dispatcher-shared-id';

  type Step = 'legitimate' | 'mismatched' | 'redelivery';
  const orderings = permutations<Step>(['legitimate', 'mismatched', 'redelivery']);

  it.each(orderings.map((ordering, index) => ({ index, ordering })))(
    'ordering #$index ($ordering)',
    async ({ ordering }) => {
      const handleSpy = vi.fn();
      const dispatcher = createDispatcher([{ kind: 9, handle: handleSpy }]);
      const group = makeFakeDispatcherGroup();
      const ctx = makeCtx();
      dispatcher.subscribe(group as never, ctx);

      for (const step of ordering) {
        const claimedPubkey = step === 'mismatched' ? attackerPubkey : legitPubkey;
        const message = encodeRumor({
          id: sharedId,
          kind: 9,
          pubkey: claimedPubkey,
          created_at: 1000,
          content: 'hi',
          tags: [],
        });
        await group.emitAsync({ message, senderPubkey: legitPubkey, senderLeafIndex: 0 });
      }

      // Regardless of ordering — including "mismatched-first" — the
      // legitimate delivery is handled exactly once: the choke-point drop
      // firing before markSeen means the mismatched delivery never poisoned
      // the dedup LRU, so the legitimate rumor (whichever position it's in)
      // is never silently swallowed, and the redelivery never double-dispatches.
      expect(handleSpy).toHaveBeenCalledTimes(1);
      expect(handleSpy).toHaveBeenCalledWith(
        expect.objectContaining({ id: sharedId, pubkey: legitPubkey }),
        ctx,
        { pubkey: legitPubkey, authenticity: 'mls' },
      );
    },
  );
});

describe('AC-ORDER-1 (welcomeSubscription + dispatcher, combined real producers): a sender-mismatched raw event sharing the legitimate rumor\'s inner id never poisons either dedup layer, for every arrival order', () => {
  const legitPubkey = 'cc'.repeat(32);
  const attackerPubkey = 'dd'.repeat(32);

  type Step = 'legit' | 'mismatch' | 'redelivery';
  const orderings = permutations<Step>(['legit', 'mismatch', 'redelivery']);

  it.each(orderings.map((ordering, index) => ({ index, ordering })))(
    'ordering #$index ($ordering)',
    async ({ ordering }) => {
      const groupId = `order1-welcome-${crypto.randomUUID()}`;
      const rumorId = `${groupId}-rumor`;
      const legitRawId = `${groupId}-legit-raw`;
      const mismatchRawId = `${groupId}-mismatch-raw`;

      const { group, ingestCalls, setOutcome } = makeCombinedFakeGroup();
      setOutcome(legitRawId, { type: 'legitimate', senderPubkey: legitPubkey, rumorId });
      setOutcome(mismatchRawId, {
        type: 'mismatched',
        senderPubkey: legitPubkey,
        claimedPubkey: attackerPubkey,
        rumorId,
      });

      const handleSpy = vi.fn();
      const dispatcher = createDispatcher([{ kind: 9, handle: handleSpy }]);
      dispatcher.subscribe(group, makeCtx(groupId));

      const { ndk, liveHandlers } = makeFakeNdkWithHistorical([]);
      const unsubscribe = await subscribeToGroupMessages(groupId, ['wss://r'], group, ndk as never);

      for (const step of ordering) {
        const rawId = step === 'mismatch' ? mismatchRawId : legitRawId;
        liveHandlers[0](makeRawEvent(rawId));
        await flushPromises();
      }

      // welcomeSubscription's raw-event-id dedup: the legitimate raw event is
      // ingested exactly once (its redelivery is a dedup no-op) regardless of
      // where the mismatched raw event's delivery fell in the ordering.
      expect(ingestCalls.flat().filter((e) => e.id === legitRawId)).toHaveLength(1);
      // The mismatched raw event (a distinct outer id) is ingested exactly
      // once too — its delivery neither affects nor is affected by the
      // legitimate event's dedup entry.
      expect(ingestCalls.flat().filter((e) => e.id === mismatchRawId)).toHaveLength(1);

      // The dispatcher's per-group rumor-id LRU: the shared inner rumor id
      // reaches a handler exactly once (the legitimate delivery), never for
      // the mismatched delivery, and the redelivery never double-dispatches.
      expect(handleSpy).toHaveBeenCalledTimes(1);
      expect(handleSpy).toHaveBeenCalledWith(
        expect.objectContaining({ id: rumorId, pubkey: legitPubkey }),
        expect.anything(),
        { pubkey: legitPubkey, authenticity: 'mls' },
      );

      unsubscribe();
    },
  );
});

