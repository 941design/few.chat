// Cross-group isolation and groupId-reuse (VQ-S4-014)
// ═══════════════════════════════════════════════════════════════════════
//
// welcomeSubscription.ts's `seenIdsByGroup` is a module-level Map, keyed by
// groupId, deliberately NEVER cleared on unsubscribe (see its own header
// comment). These tests probe the two ways that persistence could go wrong:
// (a) the SAME groupId reused after a simulated dispose/re-join — does the
// shared dedup set correctly keep deduping what it already saw while still
// admitting genuinely new events? — and (b) two DIFFERENT, independently-
// keyed groups — does an id seen in one group's Set leak into another
// group's Set at all?

describe('Cross-group isolation and groupId-reuse (VQ-S4-014)', () => {
  it(
    'same groupId reused after dispose (simulated crash-recovery re-join): a previously-delivered event stays deduped on the rejoin\'s historical refetch, and a genuinely new event is still ingested and dispatched',
    async () => {
      const groupId = `order-crossgroup-reuse-${crypto.randomUUID()}`;
      const firstEventId = `${groupId}-evt-1`;
      const secondEventId = `${groupId}-evt-2`;
      const legitPubkey = 'aa'.repeat(32);

      const { group, ingestCalls, setOutcome } = makeCombinedFakeGroup();
      setOutcome(firstEventId, { type: 'legitimate', senderPubkey: legitPubkey });

      const handleSpy = vi.fn();
      const dispatcher = createDispatcher([{ kind: 9, handle: handleSpy }]);
      dispatcher.subscribe(group, makeCtx(groupId));

      // "Pre-crash" instance: sees and permanently marks firstEventId seen (a
      // non-buffered, legitimate outcome — never un-marked, per AC-ORDER-2).
      const { ndk: ndk1, liveHandlers: live1 } = makeFakeNdkWithHistorical([]);
      const unsub1 = await subscribeToGroupMessages(groupId, ['wss://r'], group, ndk1 as never);
      live1[0](makeRawEvent(firstEventId, { pubkey: legitPubkey }));
      await flushPromises();
      unsub1(); // simulated crash/teardown — does NOT clear seenIdsByGroup by design

      expect(ingestCalls.flat().filter((e) => e.id === firstEventId)).toHaveLength(1);
      expect(handleSpy).toHaveBeenCalledTimes(1);

      // "Re-join": a FRESH subscribeToGroupMessages call for the SAME
      // groupId. Its historical fetch re-observes the SAME first event
      // (still on the relay) — must be deduped, not re-ingested or
      // re-dispatched.
      setOutcome(secondEventId, { type: 'legitimate', senderPubkey: legitPubkey });
      const { ndk: ndk2, liveHandlers: live2 } = makeFakeNdkWithHistorical([
        makeRawEvent(firstEventId, { pubkey: legitPubkey }),
      ]);
      const unsub2 = await subscribeToGroupMessages(groupId, ['wss://r'], group, ndk2 as never);

      expect(ingestCalls.flat().filter((e) => e.id === firstEventId)).toHaveLength(1);
      expect(handleSpy).toHaveBeenCalledTimes(1);

      // A genuinely NEW event, never seen before the reuse, must still be
      // ingested and dispatched normally — the reused groupId's shared
      // dedup set must not have accidentally suppressed unrelated future
      // traffic.
      live2[0](makeRawEvent(secondEventId, { pubkey: legitPubkey }));
      await flushPromises();

      expect(ingestCalls.flat().filter((e) => e.id === secondEventId)).toHaveLength(1);
      expect(handleSpy).toHaveBeenCalledTimes(2);

      unsub2();
    },
  );

  it(
    'two independent groups: an event id marked seen in one group\'s dedup set does not suppress the SAME id\'s legitimate delivery in a different group',
    async () => {
      // A deliberately-colliding raw event id shared across two DISTINCT
      // groups — an edge case the codebase's own id scheme should never
      // actually produce (Nostr event ids are content hashes), but the
      // isolation guarantee should not depend on that: seenIdsByGroup is
      // keyed by groupId, so even a literal id collision across groups must
      // not cross-suppress.
      const collidingEventId = `collide-${crypto.randomUUID()}`;
      const groupA = `order-crossgroup-a-${crypto.randomUUID()}`;
      const groupB = `order-crossgroup-b-${crypto.randomUUID()}`;
      const pubkeyA = 'bb'.repeat(32);
      const pubkeyB = 'cc'.repeat(32);

      const { group: groupObjA, ingestCalls: ingestCallsA, setOutcome: setOutcomeA } = makeCombinedFakeGroup();
      setOutcomeA(collidingEventId, { type: 'legitimate', senderPubkey: pubkeyA });
      const { group: groupObjB, ingestCalls: ingestCallsB, setOutcome: setOutcomeB } = makeCombinedFakeGroup();
      setOutcomeB(collidingEventId, { type: 'legitimate', senderPubkey: pubkeyB });

      // One shared dispatcher instance handling both groups — mirrors
      // production (a single app-wide dispatcher subscribed per active group).
      const handleSpyA = vi.fn();
      const handleSpyB = vi.fn();
      const dispatcher = createDispatcher([
        {
          kind: 9,
          handle: (rumor, ctx, sender) =>
            ctx.groupId === groupA ? handleSpyA(rumor, ctx, sender) : handleSpyB(rumor, ctx, sender),
        },
      ]);
      dispatcher.subscribe(groupObjA, makeCtx(groupA));
      dispatcher.subscribe(groupObjB, makeCtx(groupB));

      const { ndk: ndkA, liveHandlers: liveA } = makeFakeNdkWithHistorical([]);
      const unsubA = await subscribeToGroupMessages(groupA, ['wss://r'], groupObjA, ndkA as never);
      liveA[0](makeRawEvent(collidingEventId, { pubkey: pubkeyA }));
      await flushPromises();

      expect(ingestCallsA.flat().filter((e) => e.id === collidingEventId)).toHaveLength(1);
      expect(handleSpyA).toHaveBeenCalledTimes(1);

      // Group B observes the SAME literal event id — group A having marked
      // it seen must have zero effect on group B's independent dedup set.
      const { ndk: ndkB, liveHandlers: liveB } = makeFakeNdkWithHistorical([]);
      const unsubB = await subscribeToGroupMessages(groupB, ['wss://r'], groupObjB, ndkB as never);
      liveB[0](makeRawEvent(collidingEventId, { pubkey: pubkeyB }));
      await flushPromises();

      expect(ingestCallsB.flat().filter((e) => e.id === collidingEventId)).toHaveLength(1);
      expect(handleSpyB).toHaveBeenCalledTimes(1);
      // Group A's handler must never have fired for group B's delivery.
      expect(handleSpyA).toHaveBeenCalledTimes(1);

      unsubA();
      unsubB();
    },
  );
});
