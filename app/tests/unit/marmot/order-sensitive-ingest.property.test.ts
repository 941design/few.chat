/** Exhaustive permutations — the hand-rolled substitute for a property
 * generator (no fast-check dependency; see header note). */
function permutations<T>(arr: T[]): T[][] {
  if (arr.length <= 1) return [arr];
  const result: T[][] = [];
  for (let i = 0; i < arr.length; i++) {
    const rest = [...arr.slice(0, i), ...arr.slice(i + 1)];
    for (const perm of permutations(rest)) {
      result.push([arr[i], ...perm]);
    }
  }
  return result;
}

/** Drain pending microtasks/macrotasks so async listener chains complete. */
async function flushPromises(rounds = 5): Promise<void> {
  for (let i = 0; i < rounds; i++) {
    await new Promise<void>((resolve) => setTimeout(resolve, 0));
  }
}

function makeRawEvent(id: string, overrides: Partial<NostrEvent> = {}): NostrEvent {
  return {
    id,
    pubkey: overrides.pubkey ?? 'raw-pk',
    created_at: overrides.created_at ?? 1000,
    kind: overrides.kind ?? 445,
    tags: overrides.tags ?? [],
    content: overrides.content ?? '',
    sig: overrides.sig ?? 'sig',
  };
}

function encodeRumor(rumor: {
  id: string;
  kind: number;
  pubkey: string;
  created_at: number;
  content: string;
  tags: string[][];
}): Uint8Array {
  return new TextEncoder().encode(JSON.stringify(rumor));
}

